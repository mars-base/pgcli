package podman

import (
	"fmt"
	"path/filepath"
	"strings"
	"syscall"

	"github.com/mars-base/pgcli/internal/config"
)

// In-container mount points for the Garage dirs, matching the upstream docs'
// layout (/var/lib/garage/{meta,data}). The rendered garage.toml refers to
// these, not the host paths — the config is written with container-side
// coordinates on purpose so the host dirs can live anywhere under base-dir.
const (
	garageContainerMetaDir = "/var/lib/garage/meta"
	garageContainerDataDir = "/var/lib/garage/data"
	garageContainerConfig  = "/etc/garage.toml"
)

// garageBindAddr formats a host:port pair the way Garage's TOML bind_addr
// values want it: an IPv6 literal (or the dual-stack wildcard) is bracketed.
// proxyBindHost already widens loopback/empty binds to 0.0.0.0 for the bridge
// path, so the host here is never empty.
func garageBindAddr(host string, port int) string {
	if strings.Contains(host, ":") {
		return fmt.Sprintf("[%s]:%d", host, port)
	}
	return fmt.Sprintf("%s:%d", host, port)
}

// containerGarageDataDirs is the in-container path for each data drive: the
// single-dir case keeps the constant /var/lib/garage/data; drive i of a
// multi-disk node mounts at .../data(i+1), the same slot scheme the seaweedfs
// and minio managers use. It depends only on the drive COUNT, so the TOML
// render, the mount loop and the CLI display can all call it and stay in
// lockstep. Exported as GarageContainerDataDirs for the display callers.
func containerGarageDataDirs(n int) []string {
	if n <= 1 {
		return []string{garageContainerDataDir}
	}
	out := make([]string, n)
	for i := range out {
		out[i] = fmt.Sprintf("%s%d", garageContainerDataDir, i+1)
	}
	return out
}

// GarageContainerDataDirs returns the in-container data_dir slots for a node
// with n host drives (see containerGarageDataDirs).
func GarageContainerDataDirs(n int) []string { return containerGarageDataDirs(n) }

// driveCapacityGiB returns the usable size of the filesystem holding path, in
// GiB rounded down (floor 1). A not-yet-created dir resolves against its
// nearest existing ancestor (an eventual mount there changes the number, not
// the legality). Garage v2.4 REQUIRES a capacity on every data_dir array
// entry — an entry without one (and not read_only) refuses to boot, verified
// on vm01 — and pgcli has no knob for it, so each drive is charged its whole
// filesystem, which is what a "one dir per separately-mounted disk" layout
// wants.
func driveCapacityGiB(path string) (uint64, error) {
	p := filepath.Clean(path)
	var st syscall.Statfs_t
	for {
		if err := syscall.Statfs(p, &st); err == nil {
			break
		}
		parent := filepath.Dir(p)
		if parent == p {
			return 0, fmt.Errorf("statfs %s: no existing parent to size", path)
		}
		p = parent
	}
	// Bsize/Bavail types differ across platforms (linux int64/uint64, darwin
	// uint32) — widen both before multiplying. Floor at 1 GiB so an
	// essentially-full or tiny fs still yields a positive capacity Garage accepts.
	return max(uint64(st.Bsize)*uint64(st.Bavail)/(1<<30), 1), nil
}

// renderGarageTOML builds the garage.toml content for one instance. bind is
// the in-container bind address (see garageBindAddr); the dirs are the fixed
// container mount points (metadata_dir always; data_dir as one path or, with
// Drives set, an array of per-disk tables). capacities pairs 1:1 with
// gc.Drives (GiB, see driveCapacityGiB) and is ignored in the single-dir
// case. Secrets live in the file (rpc_secret), so callers must write it 0600 —
// Garage refuses a world-readable config that carries secrets.
func renderGarageTOML(gc *config.GarageConfig, bind string, capacities []uint64) string {
	var b strings.Builder
	b.WriteString("# Generated by pgcli — edit the pg.yaml garage entry and re-run\n")
	b.WriteString("# `pg addon install garage` instead; this file is rewritten.\n")
	b.WriteString("\n")
	fmt.Fprintf(&b, "metadata_dir = %q\n", garageContainerMetaDir)
	// data_dir has two legal shapes: a single path string, or (since Garage
	// v0.9.0) an array of { path = …, capacity = … } tables, one per disk.
	// pgcli emits the array only when drives are configured; capacity is
	// MANDATORY on every entry (v2.4 refuses the entry without one, verified
	// on vm01) and pgcli charges each dir its whole filesystem.
	if n := len(gc.Drives); n > 1 {
		b.WriteString("data_dir = [\n")
		slots := containerGarageDataDirs(n)
		for i, d := range slots {
			fmt.Fprintf(&b, "  { path = %q, capacity = %q },\n", d, fmt.Sprintf("%dG", capacities[i]))
		}
		b.WriteString("]\n")
	} else {
		fmt.Fprintf(&b, "data_dir = %q\n", containerGarageDataDirs(n)[0])
	}
	b.WriteString("db_engine = \"lmdb\"\n")
	fmt.Fprintf(&b, "replication_factor = %d\n", gc.ReplicationFactor)
	b.WriteString("\n")
	fmt.Fprintf(&b, "rpc_bind_addr = %q\n", garageBindAddr(rpcBindHost(gc, bind), gc.RPCPort))
	// rpc_public_addr is the address peers dial — required for a cluster (each
	// node advertises its reachable host), omitted for single-node (loopback
	// only, no peers). Empty when AdvertiseHost is unset.
	if pub := gc.RPCPublicAddr(); pub != "" {
		fmt.Fprintf(&b, "rpc_public_addr = %q\n", pub)
	}
	fmt.Fprintf(&b, "rpc_secret = %q\n", gc.RPCSecret)
	b.WriteString("\n")
	b.WriteString("[s3_api]\n")
	fmt.Fprintf(&b, "s3_region = %q\n", gc.Region)
	fmt.Fprintf(&b, "api_bind_addr = %q\n", garageBindAddr(bind, gc.APIPort))
	b.WriteString("\n")
	b.WriteString("[s3_web]\n")
	fmt.Fprintf(&b, "bind_addr = %q\n", garageBindAddr(bind, gc.WebPort))
	// root_domain is a required field of [s3_web] since Garage v2.1 (TOML
	// decode refuses without it); it only names the vhost suffix for bucket
	// website hosting, which a loopback single-node store never serves.
	b.WriteString("root_domain = \"garage.localhost\"\n")
	b.WriteString("index = \"index.html\"\n")
	b.WriteString("\n")
	b.WriteString("[admin]\n")
	fmt.Fprintf(&b, "api_bind_addr = %q\n", garageBindAddr(bind, gc.AdminPort))
	return b.String()
}

// garageMountFlags binds the metadata dir plus one mount per data drive
// (writable — drive i lands at its own /var/lib/garage/data[i+1] slot, or the
// bare .../data when there is only one), and the rendered config (read-only:
// Garage never writes /etc/garage.toml) into the container. hostDataDirs must
// match the count containerGarageDataDirs was called with.
func garageMountFlags(hostMetaDir string, hostDataDirs []string, hostConfigFile string) []string {
	flags := []string{
		"-v", fmt.Sprintf("%s:%s:z", hostMountPath(hostMetaDir), garageContainerMetaDir),
	}
	for i, d := range hostDataDirs {
		flags = append(flags, "-v", fmt.Sprintf("%s:%s:z", hostMountPath(d), containerGarageDataDirs(len(hostDataDirs))[i]))
	}
	return append(flags, "-v", fmt.Sprintf("%s:%s:ro,z", hostMountPath(hostConfigFile), garageContainerConfig))
}

// rpcBindHost picks the rpc_bind_addr host. A cluster member's RPC port is
// what peers dial (rpc_public_addr advertises it), so a loopback Listen must
// NOT pin RPC to loopback — widening only the bind, not the advertised addr,
// keeps the S3 API/web/admin ports exactly where the operator set them. The
// RPC channel is signed with rpc_secret, so opening it on the network is
// garage's own recommended cluster posture. IPv6 advertise hosts widen to the
// dual-stack wildcard instead of the IPv4 one.
func rpcBindHost(gc *config.GarageConfig, bind string) string {
	if !gc.Clustered() {
		return bind
	}
	switch bind {
	case "", "127.0.0.1", "localhost", "::1":
		if strings.Contains(gc.AdvertiseHost, ":") {
			return "::"
		}
		return "0.0.0.0"
	}
	return bind
}

// Garage's own first-boot seed (GARAGE_DEFAULT_ACCESS_KEY / _SECRET_KEY, the
// single-node path) enforces these id/secret length floors; pgcli repeats them
// up front so a too-short --root-user/--root-password fails the install loudly
// instead of leaving a detached container crash-looping on `--restart
// unless-stopped` behind a successful-looking install summary.
const (
	garageMinAccessKeyLen = 8
	garageMinSecretKeyLen = 16
)

// ValidateGarageCluster gates a Garage install for either topology.
// Single-node (Cluster empty): replication_factor must be ≤ 1 — that is the v1
// contract, reworded; a supplied --root-user/--root-password must clear
// Garage's length floors (empty is fine — the install generates them). Cluster
// (Cluster set): the node must advertise a peer-dialable address
// (AdvertiseHost); a joiner (any known Peers) must also carry the shared
// RPCSecret — the bootstrap node has none yet because the install generates
// it. A Capacity without a Zone is rejected because `garage layout assign -c`
// requires `-z`. (pgcli v2 does not manage node removal or layout revert.)
func ValidateGarageCluster(gc *config.GarageConfig) error {
	if !gc.Clustered() {
		if gc.ReplicationFactor > 1 {
			return fmt.Errorf("garage replication_factor > 1 requires a cluster (set cluster in pg.yaml / pass --cluster); single-node must be 1, got %d", gc.ReplicationFactor)
		}
		if gc.RootUser != "" && len(gc.RootUser) < garageMinAccessKeyLen {
			return fmt.Errorf("garage access key (--root-user) must be at least %d characters (Garage rejects shorter ids on first boot): got %d", garageMinAccessKeyLen, len(gc.RootUser))
		}
		if gc.RootPassword != "" && len(gc.RootPassword) < garageMinSecretKeyLen {
			return fmt.Errorf("garage secret key (--root-password) must be at least %d characters (Garage rejects shorter secrets on first boot): got %d", garageMinSecretKeyLen, len(gc.RootPassword))
		}
		return nil
	}
	if gc.AdvertiseHost == "" {
		return fmt.Errorf("garage cluster %q requires --advertise-host <this node's peer-reachable IP> (rpc_public_addr)", gc.Cluster)
	}
	if gc.RPCSecret == "" && len(gc.Peers) > 0 {
		return fmt.Errorf("garage cluster %q: joining a known peer requires the cluster's shared --rpc-secret <64hex> (printed once by the bootstrap node's install summary)", gc.Cluster)
	}
	if gc.Capacity > 0 && gc.Zone == "" {
		return fmt.Errorf("garage cluster %q: --capacity requires --zone (garage layout assign refuses -c without -z)", gc.Cluster)
	}
	return nil
}
