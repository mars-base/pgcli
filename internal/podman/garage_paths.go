package podman

import (
	"fmt"
	"strings"

	"github.com/mars-base/pgcli/internal/config"
)

// In-container mount points for the Garage dirs, matching the upstream docs'
// layout (/var/lib/garage/{meta,data}). The rendered garage.toml refers to
// these, not the host paths — the config is written with container-side
// coordinates on purpose so the host dirs can live anywhere under base-dir.
const (
	garageContainerMetaDir = "/var/lib/garage/meta"
	garageContainerDataDir = "/var/lib/garage/data"
	garageContainerConfig  = "/etc/garage.toml"
)

// garageBindAddr formats a host:port pair the way Garage's TOML bind_addr
// values want it: an IPv6 literal (or the dual-stack wildcard) is bracketed.
// proxyBindHost already widens loopback/empty binds to 0.0.0.0 for the bridge
// path, so the host here is never empty.
func garageBindAddr(host string, port int) string {
	if strings.Contains(host, ":") {
		return fmt.Sprintf("[%s]:%d", host, port)
	}
	return fmt.Sprintf("%s:%d", host, port)
}

// renderGarageTOML builds the garage.toml content for one single-node instance.
// bind is the in-container bind address (see garageBindAddr); the two dirs are
// the fixed container mount points. Secrets live in the file (rpc_secret), so
// callers must write it 0600 — Garage refuses a world-readable config that
// carries secrets.
func renderGarageTOML(gc *config.GarageConfig, bind string) string {
	var b strings.Builder
	b.WriteString("# Generated by pgcli — edit the pg.yaml garage entry and re-run\n")
	b.WriteString("# `pg addon install garage` instead; this file is rewritten.\n")
	b.WriteString("\n")
	fmt.Fprintf(&b, "metadata_dir = %q\n", garageContainerMetaDir)
	fmt.Fprintf(&b, "data_dir = %q\n", garageContainerDataDir)
	b.WriteString("db_engine = \"lmdb\"\n")
	fmt.Fprintf(&b, "replication_factor = %d\n", gc.ReplicationFactor)
	b.WriteString("\n")
	fmt.Fprintf(&b, "rpc_bind_addr = %q\n", garageBindAddr(rpcBindHost(gc, bind), gc.RPCPort))
	// rpc_public_addr is the address peers dial — required for a cluster (each
	// node advertises its reachable host), omitted for single-node (loopback
	// only, no peers). Empty when AdvertiseHost is unset.
	if pub := gc.RPCPublicAddr(); pub != "" {
		fmt.Fprintf(&b, "rpc_public_addr = %q\n", pub)
	}
	fmt.Fprintf(&b, "rpc_secret = %q\n", gc.RPCSecret)
	b.WriteString("\n")
	b.WriteString("[s3_api]\n")
	fmt.Fprintf(&b, "s3_region = %q\n", gc.Region)
	fmt.Fprintf(&b, "api_bind_addr = %q\n", garageBindAddr(bind, gc.APIPort))
	b.WriteString("\n")
	b.WriteString("[s3_web]\n")
	fmt.Fprintf(&b, "bind_addr = %q\n", garageBindAddr(bind, gc.WebPort))
	// root_domain is a required field of [s3_web] since Garage v2.1 (TOML
	// decode refuses without it); it only names the vhost suffix for bucket
	// website hosting, which a loopback single-node store never serves.
	b.WriteString("root_domain = \"garage.localhost\"\n")
	b.WriteString("index = \"index.html\"\n")
	b.WriteString("\n")
	b.WriteString("[admin]\n")
	fmt.Fprintf(&b, "api_bind_addr = %q\n", garageBindAddr(bind, gc.AdminPort))
	return b.String()
}

// garageMountFlags binds the two data dirs (writable) and the rendered config
// (read-only: Garage never writes /etc/garage.toml) into the container.
func garageMountFlags(hostMetaDir, hostDataDir, hostConfigFile string) []string {
	return []string{
		"-v", fmt.Sprintf("%s:%s:z", hostMountPath(hostMetaDir), garageContainerMetaDir),
		"-v", fmt.Sprintf("%s:%s:z", hostMountPath(hostDataDir), garageContainerDataDir),
		"-v", fmt.Sprintf("%s:%s:ro,z", hostMountPath(hostConfigFile), garageContainerConfig),
	}
}

// rpcBindHost picks the rpc_bind_addr host. A cluster member's RPC port is
// what peers dial (rpc_public_addr advertises it), so a loopback Listen must
// NOT pin RPC to loopback — widening only the bind, not the advertised addr,
// keeps the S3 API/web/admin ports exactly where the operator set them. The
// RPC channel is signed with rpc_secret, so opening it on the network is
// garage's own recommended cluster posture. IPv6 advertise hosts widen to the
// dual-stack wildcard instead of the IPv4 one.
func rpcBindHost(gc *config.GarageConfig, bind string) string {
	if !gc.Clustered() {
		return bind
	}
	switch bind {
	case "", "127.0.0.1", "localhost", "::1":
		if strings.Contains(gc.AdvertiseHost, ":") {
			return "::"
		}
		return "0.0.0.0"
	}
	return bind
}

// ValidateGarageCluster gates a Garage install for either topology.
// Single-node (Cluster empty): replication_factor must be ≤ 1 — that is the v1
// contract, reworded. Cluster (Cluster set): the node must advertise a
// peer-dialable address (AdvertiseHost); a joiner (any known Peers) must also
// carry the shared RPCSecret — the bootstrap node has none yet because the
// install generates it. A Capacity without a Zone is rejected because
// `garage layout assign -c` requires `-z`. (pgcli v2 does not manage node
// removal or layout revert.)
func ValidateGarageCluster(gc *config.GarageConfig) error {
	if !gc.Clustered() {
		if gc.ReplicationFactor > 1 {
			return fmt.Errorf("garage replication_factor > 1 requires a cluster (set cluster in pg.yaml / pass --cluster); single-node must be 1, got %d", gc.ReplicationFactor)
		}
		return nil
	}
	if gc.AdvertiseHost == "" {
		return fmt.Errorf("garage cluster %q requires --advertise-host <this node's peer-reachable IP> (rpc_public_addr)", gc.Cluster)
	}
	if gc.RPCSecret == "" && len(gc.Peers) > 0 {
		return fmt.Errorf("garage cluster %q: joining a known peer requires the cluster's shared --rpc-secret <64hex> (printed once by the bootstrap node's install summary)", gc.Cluster)
	}
	if gc.Capacity > 0 && gc.Zone == "" {
		return fmt.Errorf("garage cluster %q: --capacity requires --zone (garage layout assign refuses -c without -z)", gc.Cluster)
	}
	return nil
}
