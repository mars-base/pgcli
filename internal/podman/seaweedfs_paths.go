// In-container paths for the SeaweedFS rendered files. The lookup paths for
// s3.json and filer.toml are baked into weed (it searches /etc/seaweedfs/),
// and the TLS file names (cert.pem/key.pem) are pgcli's choice — weed takes
// -s3.cert.file/-s3.key.file explicitly, so the names only have to match the
// flags createContainer passes.
const (
	seaweedContainerDataDir  = "/data"
	seaweedContainerS3Config = "/etc/seaweedfs/s3.json"
	seaweedContainerFilerCfg = "/etc/seaweedfs/filer.toml"
	seaweedContainerCert     = "/etc/seaweedfs/cert.pem"
	seaweedContainerKey      = "/etc/seaweedfs/key.pem"
)

// pgcli's own credential floors, copied from garage's (garageMinAccessKeyLen /
// garageMinSecretKeyLen): S3 itself tolerates shorter keys, but a typo-short
// --root-user/--root-password would just leave a detached container
// crash-looping behind --restart unless-stopped, so gate the same way.
const (
	seaweedMinAccessKeyLen = 8
	seaweedMinSecretKeyLen = 16
)

// --- s3.json rendering --------------------------------------------------

// SeaweedFS 4.48 deserialises s3.json with protojson over weed/pb/iam.proto
// (S3ApiConfiguration), verified live on vm01: `credentials` is an ARRAY of
// {accessKey, secretKey} (lowerCamelCase), and Identity has NO `buckets`
// field — per-bucket action maps died with the old doc format; a bare "Admin"
// action (s3_constants.ACTION_ADMIN) short-circuits Identity.CanDo() to full
// access, which is exactly pgcli's single-root-identity posture.
type seaweedS3Credential struct {
	AccessKey string `json:"accessKey"`
	SecretKey string `json:"secretKey"`
}

type seaweedS3Identity struct {
	Name        string                `json:"name"`
	Credentials []seaweedS3Credential `json:"credentials"`
	Actions     []string              `json:"actions"`
}

type seaweedS3Config struct {
	Identities []seaweedS3Identity `json:"identities"`
}

// renderSeaweedS3JSON builds the s3.json content for one root identity with
// Admin actions. The file carries the secret key, so callers write it 0600.
func renderSeaweedS3JSON(sc *config.SeaweedfsConfig) (string, error) {
	doc := seaweedS3Config{
		Identities: []seaweedS3Identity{{
			Name: sc.Name,
			Credentials: []seaweedS3Credential{{
				AccessKey: sc.RootUser,
				SecretKey: sc.RootPassword,
			}},
			Actions: []string{"Admin"},
		}},
	}
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return "", fmt.Errorf("rendering seaweedfs s3.json: %w", err)
	}
	return string(b) + "\n", nil
}

// --- filer.toml rendering ------------------------------------------------

// renderSeaweedFilerTOML builds the [postgres2] filer-store config for a
// shared external PostgreSQL. Key names match 4.48
// weed/filer/postgres2/postgres2_store.go verbatim (hostname/port/username/
// password/database/sslmode — there is NO dsn key; old wiki examples lie).
// Connection-pool sizes are deliberately not rendered: 4.48 defaults
// connection_max_idle=50/lifetime=300s and leaves connection_max_open
// UNBOUNDED on purpose — the source comments that a bounded pool deadlocks
// directory listings (a listing runs a second query from its own callback).
// The file embeds the metadata password, so callers write it 0600.
func renderSeaweedFilerTOML(host string, port int, user, password, database string) string {
	var b strings.Builder
	b.WriteString("# Generated by pgcli — edit the pg.yaml seaweedfs entry and re-run\n")
	b.WriteString("# `pg addon install seaweedfs` instead; this file is rewritten.\n")
	b.WriteString("\n")
	b.WriteString("[postgres2]\n")
	b.WriteString("enabled = true\n")
	fmt.Fprintf(&b, "hostname = %q\n", host)
	fmt.Fprintf(&b, "port = %d\n", port)
	fmt.Fprintf(&b, "username = %q\n", user)
	fmt.Fprintf(&b, "password = %q\n", password)
	fmt.Fprintf(&b, "database = %q\n", database)
	// pgcli's own instances serve plaintext on the host network; a TLS-only
	// remote metadata DB is a v1 limitation (documented).
	b.WriteString("sslmode = \"disable\"\n")
	return b.String()
}

// --- peers ---------------------------------------------------------------

// NormalizeSeaweedfsPeers folds this node's own AdvertiseHost:Port into the
// configured peer list (weed requires the FULL Raft list on every member,
// MNMD-style), deduplicates, and sorts so the flag string is deterministic
// across nodes and reruns.
func NormalizeSeaweedfsPeers(sc *config.SeaweedfsConfig) []string {
	if !sc.Clustered() {
		return nil
	}
	peers := make([]string, 0, len(sc.Peers)+1)
	peers = append(peers, sc.Peers...)
	peers = append(peers, fmt.Sprintf("%s:%d", sc.AdvertiseHost, sc.Port))
	out := make([]string, 0, len(peers))
	for _, p := range peers {
		p = strings.TrimSpace(p)
		if p == "" || slices.Contains(out, p) {
			continue
		}
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

// SeaweedfsPeersFlag is the -master.peers argv value.
func SeaweedfsPeersFlag(sc *config.SeaweedfsConfig) string {
	return strings.Join(NormalizeSeaweedfsPeers(sc), ",")
}

// --- install validation ----------------------------------------------------

var seaweedReplicationRe = regexp.MustCompile(`^[0-3]{1,3}$`)

// ValidateSeaweedfsCluster gates a SeaweedFS install for either topology
// (mirrors ValidateGarageCluster's shape and the same crash-loop rationale).
// Single-node: placement must be "000" — with one node every other code
// guarantees "no sufficient volumes found" on the first write. Cluster: this
// node must advertise a peer-dialable -ip (AdvertiseHost), the FULL Raft list
// must name at least two members, the placement code must be well-formed, and
// the shared filer PostgreSQL is REQUIRED — every node fronts filer+S3, so
// per-node local metadata (leveldb2) would fork the namespace immediately.
// A supplied access/secret key must clear the length floors. Empty creds are
// fine single-node (the install generates them) but are an error for a
// cluster: see the shared-credential rule below.
func ValidateSeaweedfsCluster(sc *config.SeaweedfsConfig) error {
	if sc.RootUser != "" && len(sc.RootUser) < seaweedMinAccessKeyLen {
		return fmt.Errorf("seaweedfs access key (--root-user) must be at least %d characters: got %d", seaweedMinAccessKeyLen, len(sc.RootUser))
	}
	if sc.RootPassword != "" && len(sc.RootPassword) < seaweedMinSecretKeyLen {
		return fmt.Errorf("seaweedfs secret key (--root-password) must be at least %d characters: got %d", seaweedMinSecretKeyLen, len(sc.RootPassword))
	}
	if !sc.Clustered() {
		if sc.Replication != "" && sc.Replication != "000" {
			return fmt.Errorf("seaweedfs single-node requires replication 000 (no peers to replicate to); got %q — pass --cluster to create a multi-node cluster", sc.Replication)
		}
		return nil
	}
	if sc.AdvertiseHost == "" {
		return fmt.Errorf("seaweedfs cluster %q requires --advertise-host <this node's peer-reachable IP> (weed -ip that peers dial)", sc.Cluster)
	}
	if !seaweedReplicationRe.MatchString(sc.Replication) {
		return fmt.Errorf("seaweedfs cluster %q: replication must be a 1-3 digit placement code of 0-3 (e.g. 001 = one remote copy, 010 = two racks), got %q", sc.Cluster, sc.Replication)
	}
	if len(NormalizeSeaweedfsPeers(sc)) < 2 {
		return fmt.Errorf("seaweedfs cluster %q needs at least 2 peers (this node plus one --peer <ip:port>)", sc.Cluster)
	}
	if sc.FilerDSN == "" {
		return fmt.Errorf("seaweedfs cluster %q requires a shared filer metadata database: pass --dsn postgres://... (reachable from every host; the operator pre-creates the database)", sc.Cluster)
	}
	// One cluster, one credential pair: each node reads only its own s3.json
	// (there is no shared-credential backend without a standalone IAM server,
	// out of v1 scope), so auto-generating per node would leave every gateway
	// authenticating a different identity. Require explicit, identical creds.
	if sc.RootUser == "" || sc.RootPassword == "" {
		return fmt.Errorf("seaweedfs cluster %q requires explicit shared credentials: pass the SAME --root-user and --root-password on every node (generate a pair once; single-node installs may omit them and auto-generate)", sc.Cluster)
	}
	return nil
}
