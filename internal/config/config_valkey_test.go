func TestValkeyDefaults(t *testing.T) {
	cfg := Default()
	cfg.Addons.Valkey = map[string]ValkeyConfig{
		"cache": {},
	}

	cfg.ApplyDefaults()

	vc, ok := cfg.Addons.Valkey["cache"]
	if !ok {
		t.Fatal("valkey addon missing after ApplyDefaults")
	}
	if vc.Name != "cache" {
		t.Errorf("name = %q, want cache", vc.Name)
	}
	if vc.ContainerName != "pgcli-valkey-cache" {
		t.Errorf("container name = %q, want pgcli-valkey-cache", vc.ContainerName)
	}
	if vc.Version != DefaultValkeyMajor || DefaultValkeyMajor != "9" {
		t.Errorf("version = %q, want %q (default major 9)", vc.Version, DefaultValkeyMajor)
	}
	wantTag, _ := ValkeyImageTagForMajor(DefaultValkeyMajor)
	if vc.ImageTag != wantTag {
		t.Errorf("image tag = %q, want %q", vc.ImageTag, wantTag)
	}
	if vc.Listen != "0.0.0.0" {
		t.Errorf("listen = %q, want 0.0.0.0 (requirepass is the gate, so the default publishes the port)", vc.Listen)
	}
	// Password is generated by the CLI install handler, never by ApplyDefaults.
	if vc.Password != "" {
		t.Errorf("password = %q, want empty (CLI-generated)", vc.Password)
	}
	// DataDir is resolved by the manager at container-creation time.
	if vc.DataDir != "" {
		t.Errorf("data dir = %q, want empty (manager-resolved)", vc.DataDir)
	}
	if cfg.ValkeyStartPort != 6380 {
		t.Errorf("valkey start port = %d, want 6380", cfg.ValkeyStartPort)
	}
	if vc.Port < cfg.ValkeyStartPort {
		t.Errorf("port %d below base %d", vc.Port, cfg.ValkeyStartPort)
	}
}

// Version "7" resolves through the Valkey table; an explicit ImageTag is never
// rewritten, and an unknown Version with an explicit ImageTag is left alone
// (it came from --image, whose precedence the CLI enforces).
func TestValkeyVersionResolution(t *testing.T) {
	tag7, ok := ValkeyImageTagForMajor("7")
	if !ok {
		t.Fatal("major 7 missing from valkeyMajorImages")
	}

	cfg := Default()
	cfg.Addons.Valkey = map[string]ValkeyConfig{
		"legacy":  {Version: "7"},
		"custom":  {Version: "7", ImageTag: "registry.local/valkey:7.2.4"},
		"weird":   {Version: "10", ImageTag: "docker.io/valkey/valkey:10.0.0"},
		"noimage": {Version: "10"},
	}

	cfg.ApplyDefaults()

	if got := cfg.Addons.Valkey["legacy"]; got.ImageTag != tag7 || got.Version != "7" {
		t.Errorf("legacy = version %q tag %q, want 7 / %q", got.Version, got.ImageTag, tag7)
	}
	if got := cfg.Addons.Valkey["custom"]; got.ImageTag != "registry.local/valkey:7.2.4" {
		t.Errorf("explicit image tag rewritten: %q", got.ImageTag)
	}
	if got := cfg.Addons.Valkey["weird"]; got.ImageTag != "docker.io/valkey/valkey:10.0.0" || got.Version != "10" {
		t.Errorf("unknown version with explicit tag mutated: version=%q tag=%q", got.Version, got.ImageTag)
	}
	// Unknown version without a tag stays empty so the install surfaces as an
	// image-not-found pull error, not a silent rewrite.
	if got := cfg.Addons.Valkey["noimage"]; got.ImageTag != "" {
		t.Errorf("unknown version without tag backfilled to %q, want empty", got.ImageTag)
	}
}

func TestValkeySaveLoadRoundTrip(t *testing.T) {
	path := filepath.Join(t.TempDir(), "pg.yaml")

	cfg := Default()
	cfg.ValkeyStartPort = 36380
	cfg.Addons.Valkey = map[string]ValkeyConfig{
		"cache": {
			ContainerName:   "pgcli-valkey-cache",
			Name:            "cache",
			Version:         "7",
			ImageTag:        valkeyMajorImages["7"],
			DataDir:         "/srv/valkey/cache",
			Listen:          "127.0.0.1",
			Port:            36399,
			Password:        "aX9kQ2mZx7Lp4RtVbNcE",
			MaxMemory:       "256mb",
			AOF:             true,
			AppendFsync:     "always",
			MaxMemoryPolicy: "noeviction",
			SaveSchedule:    "900 1 300 10",
			Autostart:       true,
		},
		// The replica role is stored, not re-derived: `pg addon start` rebuilds
		// --replicaof from these two fields with no master lookup.
		"cache-r": {
			ContainerName: "pgcli-valkey-cache-r",
			Name:          "cache-r",
			Version:       "7",
			ImageTag:      valkeyMajorImages["7"],
			Port:          36400,
			Password:      "aX9kQ2mZx7Lp4RtVbNcE",
			ReplicaHost:   "127.0.0.1",
			ReplicaPort:   36399,
		},
		// Cluster membership and its intent fields survive too.
		"n1": {
			ContainerName:   "pgcli-valkey-n1",
			Name:            "n1",
			Cluster:         "app",
			ClusterReplicas: 1,
			AdvertiseHost:   "10.10.0.159",
			Port:            36479,
			Password:        "shared-cluster-pw",
		},
	}
	if err := cfg.Save(path); err != nil {
		t.Fatalf("save: %v", err)
	}

	got, err := Load(path)
	if err != nil {
		t.Fatalf("load: %v", err)
	}
	vc, ok := got.Addons.Valkey["cache"]
	if !ok {
		t.Fatal("valkey addon not persisted")
	}
	if vc.Version != "7" || vc.ImageTag != valkeyMajorImages["7"] {
		t.Errorf("version/image not persisted: %q / %q", vc.Version, vc.ImageTag)
	}
	if vc.Port != 36399 {
		t.Errorf("port not persisted: %d", vc.Port)
	}
	if vc.Password != "aX9kQ2mZx7Lp4RtVbNcE" {
		t.Errorf("password not persisted: %q", vc.Password)
	}
	if vc.MaxMemory != "256mb" || vc.MaxMemoryPolicy != "noeviction" {
		t.Errorf("maxmemory knobs not persisted: %q / %q", vc.MaxMemory, vc.MaxMemoryPolicy)
	}
	if !vc.AOF || vc.AppendFsync != "always" {
		t.Errorf("aof knobs not persisted: %v / %q", vc.AOF, vc.AppendFsync)
	}
	if vc.SaveSchedule != "900 1 300 10" {
		t.Errorf("save not persisted: %q", vc.SaveSchedule)
	}
	if vc.Listen != "127.0.0.1" || vc.DataDir != "/srv/valkey/cache" || !vc.Autostart {
		t.Errorf("listen/data/autostart not persisted: %q / %q / %v", vc.Listen, vc.DataDir, vc.Autostart)
	}
	if rr := got.Addons.Valkey["cache-r"]; rr.ReplicaHost != "127.0.0.1" || rr.ReplicaPort != 36399 {
		t.Errorf("replica target not persisted: %q:%d", rr.ReplicaHost, rr.ReplicaPort)
	}
	n1 := got.Addons.Valkey["n1"]
	if n1.Cluster != "app" || n1.AdvertiseHost != "10.10.0.159" || n1.ClusterReplicas != 1 {
		t.Errorf("cluster fields not persisted: %q / %q / %d", n1.Cluster, n1.AdvertiseHost, n1.ClusterReplicas)
	}
	if got.ValkeyStartPort != 36380 {
		t.Errorf("valkey_start_port not persisted: %d", got.ValkeyStartPort)
	}

	// A second ApplyDefaults must not move the assigned port, rewrite the
	// version, or touch the stored password.
	got.ApplyDefaults()
	again := got.Addons.Valkey["cache"]
	if again.Port != 36399 || again.Version != "7" || again.Password != "aX9kQ2mZx7Lp4RtVbNcE" {
		t.Errorf("ApplyDefaults mutated stored values: port=%d version=%q", again.Port, again.Version)
	}
}

// Valkey owns its port pool (valkey_start_port) and must skip both explicit
// valkey ports and the redis pool's allocations. A high unused base keeps the
// live-listener scan from perturbing exact expectations.
func TestValkeyPortAssignment(t *testing.T) {
	cfg := Default()
	cfg.RedisStartPort = 36379
	cfg.ValkeyStartPort = 36380
	cfg.Addons.Redis = map[string]RedisConfig{
		// A redis instance parked at the valkey base must be skipped.
		"r": {Port: 36380},
	}
	cfg.Addons.Valkey = map[string]ValkeyConfig{
		"a": {},            // auto: must skip the redis 36380 and b's 36381
		"b": {Port: 36381}, // explicit reservation inside the base range
		"c": {},            // auto, drawn last
	}

	cfg.ApplyDefaults()

	if got := cfg.Addons.Valkey["b"]; got.Port != 36381 {
		t.Errorf("explicit port changed: %d", got.Port)
	}
	if got := cfg.Addons.Valkey["a"]; got.Port != 36382 {
		t.Errorf("a port = %d, want 36382 (cursor must skip the redis allocation at 36380 and b's 36381)", got.Port)
	}
	if got := cfg.Addons.Valkey["c"]; got.Port != 36383 {
		t.Errorf("c port = %d, want 36383", got.Port)
	}
	if got := cfg.Addons.Redis["r"]; got.Port != 36380 {
		t.Errorf("redis explicit port changed: %d", got.Port)
	}
}

func TestValkeyMajorForImageTag(t *testing.T) {
	cases := []struct {
		imageTag string
		want     string
	}{
		{"docker.io/valkey/valkey:7.2.16", "7"},
		{"docker.io/valkey/valkey:8.1.12", "8"},
		{"docker.io/valkey/valkey:9.2.0", "9"},
		{"valkey/valkey:9", "9"},
		{"docker.io/valkey/valkey:10.0.0", ""}, // major not in the table
		{"docker.io/valkey/valkey:latest", ""}, // not a digit run
		{"docker.io/valkey/valkey", ""},        // no tag separator
	}
	for _, tc := range cases {
		if got := ValkeyMajorForImageTag(tc.imageTag); got != tc.want {
			t.Errorf("ValkeyMajorForImageTag(%q) = %q, want %q", tc.imageTag, got, tc.want)
		}
	}
}

func TestValkeyMajors(t *testing.T) {
	majors := ValkeyMajors()
	if len(majors) != len(valkeyMajorImages) {
		t.Fatalf("ValkeyMajors returned %d entries, table has %d", len(majors), len(valkeyMajorImages))
	}
	want := []string{"7", "8", "9"}
	for i, m := range want {
		if i >= len(majors) || majors[i] != m {
			t.Fatalf("ValkeyMajors = %v, want %v", majors, want)
		}
	}
	if _, ok := ValkeyImageTagForMajor("6"); ok {
		t.Error("major 6 unexpectedly resolvable")
	}
	if tag, _ := ValkeyImageTagForMajor("9"); tag != "docker.io/valkey/valkey:9.2.0" {
		t.Errorf("major 9 tag = %q, want docker.io/valkey/valkey:9.2.0", tag)
	}
}
